function build(country){
 const entry=window.WinoWattShelfOldWorld?.countries?.[country];
 if(!entry)return null;
 const items=entry.regions.map(([region,style],i)=>({id:country+'-'+i,region,style}));
 return {country,items,practice:cases[country]};
}
function directions(items){
 const flags=items.map((_,i)=>i%2===1);
 for(let i=flags.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[flags[i],flags[j]]=[flags[j],flags[i]];}
 return flags;
}
window.WinoWattOldWorldGames={build,directions,cases};
