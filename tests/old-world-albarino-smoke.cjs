'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data/old-world-albarino.js'),'utf8'),ctx);
const lesson=ctx.window.WinoWattOldWorld?.spain;
assert(lesson,'Не загружен первый региональный урок');
assert.equal(lesson.guest.length,4);
assert.equal(lesson.professional.length,7);
assert(lesson.goal.length>40&&lesson.practice.situation.length>40&&lesson.practice.answer.length>70);
for(const p of lesson.professional)assert(p.title&&p.body.length>80&&p.takeaway.length>25);
for(const [,url] of lesson.sources)assert(url.startsWith('https://'),'Источник без URL');
assert(lesson.guest.some(x=>x.includes('сол')&&x.includes('доказат')),'Оговорка о солоноватости не найдена');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
assert(html.includes('data/old-world-albarino.js'),'Не подключены данные');
assert(app.includes("window.WinoWattOldWorld?.spain"),'Региональный урок не подключён в экран');
assert(app.includes("name==='Испания'")&&app.includes("storyExample()"),'Нет входа в историю Альбариньо');
assert(app.includes("storyExample(id)"),'Нет переключения двух регистров');
vm.runInNewContext(fs.readFileSync(path.join(root,'data/old-world-shelf.js'),'utf8'),ctx);
const shelf=ctx.window.WinoWattShelfOldWorld;
const expected=['Франция','Испания','Италия','Португалия','Германия','Австрия','Грузия'];
const countries=Object.keys(shelf.countries);
assert.equal(countries.join('|'),expected.join('|'),'Порядок и состав короткого курса');
assert(!countries.some(name=>['Венгрия','Румыния','Греция'].includes(name)),'Не вернулись исключённые страны');
assert(shelf.priceGuide.note.includes('НЕ собранные цены'),'Ценовой дисклеймер');
assert(shelf.priceGuide.bands.length===4,'Четыре приблизительных сегмента');
for(const country of countries){const c=shelf.countries[country];assert(c.regions.length>=3&&c.regions.length<=6,'Проверить краткость курса: '+country);assert(c.shelf&&c.service&&c.sparkling);}
assert(html.includes('data/old-world-shelf.js'),'Нет подключения полочного справочника');
assert(app.includes('showShelfCountry'),'Нет экранов по странам');
console.log('PASS: compact Old World shelf + Albariño theory, 7 countries and 4 illustrative price tiers');
