'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'data/old-world-albarino.js'),'utf8'),ctx);
const lesson=ctx.window.WinoWattOldWorld?.spain;
assert(lesson,'Не загружен первый региональный урок');
assert.equal(lesson.guest.length,4);
assert.equal(lesson.professional.length,7);
assert(lesson.goal.length>40&&lesson.practice.situation.length>40&&lesson.practice.answer.length>70);
for(const p of lesson.professional)assert(p.title&&p.body.length>80&&p.takeaway.length>25);
for(const [,url] of lesson.sources)assert(url.startsWith('https://'),'Источник без URL');
assert(lesson.guest.some(x=>x.includes('сол')&&x.includes('доказат')),'Оговорка о солоноватости не найдена');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
assert(html.includes('data/old-world-albarino.js'),'Не подключены данные');
assert(app.includes("window.WinoWattOldWorld?.spain"),'Региональный урок не подключён в экран');
assert(app.includes("name==='Испания'&&id==='old-world'?storyExample():draft"),'Нет входа из Старого Света');
assert(app.includes("storyExample(id)"),'Нет переключения двух регистров');
console.log('PASS: first Old World lesson, 4 story paragraphs, 7 professional blocks, sources and scenario');
